import {fireEvent,render,screen} from '@testing-library/react-native';
import {PrescriptionReview} from '@/src/components/PrescriptionReview';
import {prescriptionDrafts} from '@/src/lib/prescription';
import {timeWheelRowHeight} from '@/src/components/TimeWheel';
jest.mock('react-native-safe-area-context',()=>({...jest.requireActual('react-native-safe-area-context'),useSafeAreaInsets:()=>({top:0,bottom:0,left:0,right:0})}));
jest.mock('expo-crypto',()=>({randomUUID:()=> '11111111-1111-4111-8111-111111111111'}));
jest.mock('@/src/providers/AuthProvider',()=>({useAuth:()=>({session:{user:{id:'owner'}}})}));
jest.mock('@/src/providers/HealthDataProvider',()=>({useHealthData:()=>({elderly:{elderly_id:'patient',full_name:'Fixture patient'}})}));
jest.mock('@/src/lib/supabase',()=>({supabase:{rpc:jest.fn()}}));
jest.mock('@/src/lib/watch-push',()=>({isCarePushRegistered:jest.fn().mockResolvedValue(true)}));
jest.mock('@/src/lib/notifications',()=>({scheduleMedicationNotifications:jest.fn()}));
jest.mock('@/src/lib/care-files',()=>({careFileUrl:jest.fn()}));
jest.mock('@/src/components/CareImage',()=>({CareImage:()=>null}));
const drafts=prescriptionDrafts({medications:[{medication_name:'Fixture drug',frequency:'Daily',start_date:'2026-11-15',times_of_day:[]}]});
test('prescription reminder clocks use scroll wheels and commit only after Done; cancel leaves missing times blank',async()=>{
  await render(<PrescriptionReview visible drafts={drafts} path="fixture" onClose={jest.fn()} onSaved={jest.fn()}/>);
  expect(screen.getByText(/No clock times extracted/)).toBeTruthy();
  await fireEvent.press(screen.getByLabelText('Medication 1 add reminder time'));
  expect(screen.getByTestId('minute-wheel')).toBeTruthy();
  await fireEvent.press(screen.getByLabelText('Cancel choosing date and time'));
  expect(screen.getByText(/No clock times extracted/)).toBeTruthy();
  await fireEvent.press(screen.getByLabelText('Medication 1 add reminder time'));
  await fireEvent.press(screen.getByLabelText('Hour 09'));
  await fireEvent(screen.getByTestId('minute-wheel'),'momentumScrollEnd',{nativeEvent:{contentOffset:{y:42*timeWheelRowHeight}}});
  await fireEvent.press(screen.getByLabelText('AM/PM PM'));
  await fireEvent.press(screen.getByLabelText('Done choosing date and time'));
  expect(screen.getByLabelText('Medication 1 choose reminder time 1')).toBeTruthy();
  expect(screen.getByText('9:42 PM')).toBeTruthy();
  expect(screen.queryByLabelText('Medication 1 reminder times')).toBeNull();
});
test('prescription dates use a calendar, preserve blanks on cancel and can be cleared',async()=>{
  await render(<PrescriptionReview visible drafts={drafts} path="fixture" onClose={jest.fn()} onSaved={jest.fn()}/>);
  await fireEvent.press(screen.getByLabelText('Medication 1 choose start date'));
  await fireEvent.press(screen.getByLabelText('November 20, 2026'));
  await fireEvent.press(screen.getByLabelText('Done choosing date and time'));
  expect(screen.getByText(/Nov 20, 2026/)).toBeTruthy();
  expect(screen.queryByLabelText('Medication 1 Start date (YYYY-MM-DD)')).toBeNull();
  await fireEvent.press(screen.getByLabelText('Clear medication 1 Treatment start date'));
  await fireEvent.press(screen.getByLabelText('Medication 1 choose start date'));
  await fireEvent.press(screen.getByLabelText('Cancel choosing date and time'));
  expect(screen.getAllByText('Not extracted · choose date')).toHaveLength(3);
});
